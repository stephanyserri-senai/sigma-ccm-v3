import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";

const serverDir = dirname(dirname(fileURLToPath(import.meta.url)));
const projectDir = dirname(serverDir);
const reference = readFileSync(join(projectDir, "docs", "schema-completo.sql"), "utf8");
const schema = readFileSync(
  join(projectDir, "supabase", "migrations", "20261013000000_initial_schema.sql"),
  "utf8",
);

const tableNames = (sql) => [...sql.matchAll(/CREATE TABLE IF NOT EXISTS\s+(\w+)/g)]
  .map((match) => match[1]);

test("schema Supabase contém as tabelas consolidadas do SQLite", () => {
  assert.deepEqual([...tableNames(schema)].sort(), [...tableNames(reference)].sort());
});

test("schema Supabase converte identidade, blobs e datas sem sintaxe SQLite", () => {
  assert.equal(
    (schema.match(/INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g) || []).length,
    (reference.match(/INTEGER PRIMARY KEY AUTOINCREMENT/g) || []).length,
  );
  assert.equal((schema.match(/\bBYTEA\b/g) || []).length, (reference.match(/\bBLOB\b/g) || []).length);
  assert.equal(
    (schema.match(/to_char\(CURRENT_TIMESTAMP AT TIME ZONE 'UTC'/g) || []).length,
    (reference.match(/\(datetime\('now'\)\)/g) || []).length,
  );
  assert.doesNotMatch(schema, /\b(?:PRAGMA|AUTOINCREMENT|BLOB)\b|datetime\('now'\)/i);
});

test("foreign keys reference existing tables created before their dependents", () => {
  const tableDefinitions = [...schema.matchAll(
    /CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\(([\s\S]*?)(?=\nCREATE TABLE IF NOT EXISTS|\n-- Only the trusted server-side|$)/g,
  )];
  const positions = new Map(tableDefinitions.map(([_, name], index) => [name, index]));

  assert.ok(positions.get("equipes") < positions.get("usuarios"));

  for (const [, table, definition] of tableDefinitions) {
    for (const [, referencedTable] of definition.matchAll(/REFERENCES\s+(\w+)\s*\(/g)) {
      assert.ok(positions.has(referencedTable), `${table} references missing table ${referencedTable}`);
      assert.ok(
        positions.get(referencedTable) <= positions.get(table),
        `${table} references ${referencedTable} before it is created`,
      );
    }
  }
});

test("todas as tabelas Supabase têm RLS habilitado", () => {
  const tables = tableNames(schema);
  const protectedTables = [...schema.matchAll(
    /ALTER TABLE\s+(\w+)\s+ENABLE ROW LEVEL SECURITY;/g,
  )].map((match) => match[1]);

  assert.deepEqual([...protectedTables].sort(), [...tables].sort());
});
