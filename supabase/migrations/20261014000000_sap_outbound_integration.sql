ALTER TABLE ordens
  ADD COLUMN IF NOT EXISTS sap_status TEXT NOT NULL DEFAULT 'PENDENTE',
  ADD COLUMN IF NOT EXISTS sap_enviado_em TEXT,
  ADD COLUMN IF NOT EXISTS sap_ultimo_erro TEXT;

CREATE TABLE IF NOT EXISTS integracoes_sap_fila (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id INTEGER NOT NULL UNIQUE REFERENCES ordens(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'PENDENTE'
    CHECK (status IN ('PENDENTE','PROCESSANDO','ENVIADO_AO_SAP','ERRO_ORDEM_INEXISTENTE','REGISTRO_DUPLICADO','ERRO')),
  payload JSONB NOT NULL,
  tentativas INTEGER NOT NULL DEFAULT 0,
  proxima_tentativa TEXT,
  ultimo_erro TEXT,
  criado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  atualizado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_integracoes_sap_fila_status ON integracoes_sap_fila(status, proxima_tentativa);

CREATE TABLE IF NOT EXISTS integracoes_sap_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id INTEGER NOT NULL REFERENCES ordens(id) ON DELETE CASCADE,
  tentativa INTEGER NOT NULL,
  status TEXT NOT NULL,
  codigo_http INTEGER,
  resposta TEXT,
  criado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_integracoes_sap_logs_ordem ON integracoes_sap_logs(ordem_id, id);

ALTER TABLE integracoes_sap_fila ENABLE ROW LEVEL SECURITY;
ALTER TABLE integracoes_sap_logs ENABLE ROW LEVEL SECURITY;
