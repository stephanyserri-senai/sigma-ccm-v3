CREATE TABLE IF NOT EXISTS historico_status_ordem (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id INTEGER NOT NULL REFERENCES ordens(id) ON DELETE CASCADE,
  status_anterior TEXT,
  status_novo TEXT NOT NULL,
  acao TEXT NOT NULL,
  justificativa TEXT,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  data_hora TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_historico_status_ordem ON historico_status_ordem(ordem_id, id);
ALTER TABLE historico_status_ordem ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS historico_reprogramacao_ordem (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id INTEGER NOT NULL REFERENCES ordens(id) ON DELETE CASCADE,
  data_programada_anterior TEXT,
  data_fim_anterior TEXT,
  data_programada_nova TEXT NOT NULL,
  data_fim_nova TEXT,
  justificativa TEXT NOT NULL,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  data_hora TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_historico_reprogramacao_ordem ON historico_reprogramacao_ordem(ordem_id, id);
ALTER TABLE historico_reprogramacao_ordem ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS impedimentos_ordem (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id INTEGER NOT NULL REFERENCES ordens(id) ON DELETE CASCADE,
  tipo TEXT NOT NULL CHECK (tipo IN ('Material', 'Recurso', 'Segurança', 'Escopo', 'Operacional', 'Outro')),
  descricao TEXT NOT NULL,
  registrado_por INTEGER NOT NULL REFERENCES usuarios(id),
  registrado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  resolvido_por INTEGER REFERENCES usuarios(id),
  resolvido_em TEXT,
  resolucao TEXT
);
CREATE INDEX IF NOT EXISTS idx_impedimentos_ordem ON impedimentos_ordem(ordem_id, id);
ALTER TABLE impedimentos_ordem ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS pausas_execucao_om (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  execucao_id INTEGER NOT NULL REFERENCES execucoes_om(id) ON DELETE CASCADE,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  motivo TEXT NOT NULL,
  pausado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  retomado_em TEXT
);
CREATE INDEX IF NOT EXISTS idx_pausas_execucao ON pausas_execucao_om(execucao_id, id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_pausa_aberta_execucao ON pausas_execucao_om(execucao_id) WHERE retomado_em IS NULL;
ALTER TABLE pausas_execucao_om ENABLE ROW LEVEL SECURITY;
