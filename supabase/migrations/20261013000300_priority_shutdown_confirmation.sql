CREATE TABLE IF NOT EXISTS confirmacoes_paralisacao_prioridade (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  historico_prioridade_id INTEGER NOT NULL UNIQUE REFERENCES historico_prioridade(id) ON DELETE CASCADE,
  confirmado_por INTEGER NOT NULL REFERENCES usuarios(id),
  confirmado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

ALTER TABLE confirmacoes_paralisacao_prioridade ENABLE ROW LEVEL SECURITY;
