-- Fluxo simplificado: a nota gera a OM automaticamente, já priorizada, programada e atribuída
-- a um executante (de preferência da equipe responsável pelo ativo), que aceita ou recusa.

-- Equipe responsável pelo ativo: base da escolha do executante.
ALTER TABLE equipamentos ADD COLUMN IF NOT EXISTS equipe_id INTEGER REFERENCES equipes(id);

-- Preenche com a equipe que mais atuou no equipamento (sem sobrescrever o que já foi definido).
UPDATE equipamentos e SET equipe_id = h.equipe_id
FROM (
  SELECT DISTINCT ON (equipamento_id) equipamento_id, equipe_id
  FROM ordens
  WHERE equipamento_id IS NOT NULL AND equipe_id IS NOT NULL
  GROUP BY equipamento_id, equipe_id
  ORDER BY equipamento_id, COUNT(*) DESC, equipe_id
) h
WHERE e.id = h.equipamento_id AND e.equipe_id IS NULL;

-- Aceite do executante: a OM só entra no plano dele depois de aceita.
ALTER TABLE ordens ADD COLUMN IF NOT EXISTS aceita_em TEXT;

-- OMs já liberadas ou em andamento antes deste fluxo contam como aceitas.
UPDATE ordens SET aceita_em = to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
WHERE aceita_em IS NULL AND responsavel_id IS NOT NULL AND status NOT IN ('Aberta', 'Programada', 'Distribuída');

-- Recusas: o executante que recusou não recebe a mesma OM de novo na redistribuição automática.
CREATE TABLE IF NOT EXISTS recusas_ordem (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ordem_id    INTEGER NOT NULL REFERENCES ordens(id) ON DELETE CASCADE,
  usuario_id  INTEGER NOT NULL REFERENCES usuarios(id),
  motivo      TEXT NOT NULL,
  recusado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX IF NOT EXISTS idx_recusas_ordem ON recusas_ordem(ordem_id);
ALTER TABLE recusas_ordem ENABLE ROW LEVEL SECURITY;
