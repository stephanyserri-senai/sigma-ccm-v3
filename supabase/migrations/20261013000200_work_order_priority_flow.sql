CREATE TABLE IF NOT EXISTS historico_prioridade (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nota_id INTEGER REFERENCES notas(id) ON DELETE SET NULL,
  ordem_id INTEGER REFERENCES ordens(id) ON DELETE SET NULL,
  afeta_seguranca_ambiente BOOLEAN NOT NULL,
  afeta_custos BOOLEAN NOT NULL,
  afeta_producao_qualidade BOOLEAN NOT NULL,
  possui_reserva BOOLEAN NOT NULL,
  risco_iminente BOOLEAN NOT NULL,
  equipamento_monitorado BOOLEAN NOT NULL,
  recursos_disponiveis BOOLEAN NOT NULL,
  necessita_parada_programada BOOLEAN NOT NULL,
  periodicidade_parada TEXT,
  criticidade TEXT NOT NULL CHECK (criticidade IN ('A', 'B', 'C')),
  prioridade TEXT NOT NULL CHECK (prioridade IN ('IMEDIATO', 'URGENTE', 'ALTO', 'MEDIO', 'BAIXO', 'TRIMESTRAL', 'SEMESTRAL', 'ANUAL')),
  prioridade_nivel SMALLINT NOT NULL CHECK (prioridade_nivel BETWEEN 1 AND 6),
  prazo_dias SMALLINT,
  priorizado_por INTEGER NOT NULL REFERENCES usuarios(id),
  priorizado_em TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
  CHECK (nota_id IS NOT NULL OR ordem_id IS NOT NULL),
  CHECK (periodicidade_parada IS NULL OR periodicidade_parada IN ('Trimestral', 'Semestral', 'Anual'))
);

CREATE INDEX IF NOT EXISTS idx_historico_prioridade_nota ON historico_prioridade(nota_id, id);
CREATE INDEX IF NOT EXISTS idx_historico_prioridade_ordem ON historico_prioridade(ordem_id, id);
ALTER TABLE historico_prioridade ENABLE ROW LEVEL SECURITY;
